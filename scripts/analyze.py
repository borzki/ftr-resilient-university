"""Aggregate raw experiment results into tables, figures and reliability metrics.

    python scripts/analyze.py
Outputs: results/summary.json, results/results_tables.md, results/figures/*.png
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"
FIG = ROOT / "results" / "figures"
FIG.mkdir(parents=True, exist_ok=True)

COLORS = {"baseline": "#eb6834", "resilient": "#2a78d6"}
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9, "axes.edgecolor": INK2,
                     "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
                     "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True,
                     "grid.color": GRID, "grid.linewidth": 0.6, "legend.frameon": False,
                     "figure.dpi": 150})


def load(mode: str, exp: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RAW / mode).glob(f"{exp}_r*.json"))]


def agg(runs: list[dict], key: str, sub: str | None = None):
    vals = []
    for r in runs:
        s = r["summary"][sub] if sub else r["summary"]
        v = s.get(key)
        if isinstance(v, (int, float)):
            vals.append(float(v))
    if not vals:
        return None
    return {"mean": round(statistics.mean(vals), 3), "min": min(vals), "max": max(vals), "n": len(vals)}


def fmt(a, unit="", pct=False, digits=1):
    if a is None:
        return "n/a"
    f = (lambda x: f"{x * 100:.{digits}f}%") if pct else (lambda x: f"{x:.{digits}f}{unit}")
    if a["n"] > 1 and a["min"] != a["max"]:
        return f"{f(a['mean'])} ({f(a['min'])}-{f(a['max'])})"
    return f(a["mean"])


LOAD_EXPS = [("E1_instance_crash", "E1 Application instance crash"), ("E2_node_failure", "E2 Node failure"),
             ("E3_dependency_timeout", "E3 Dependency timeout"), ("E4_database_failure", "E4 Database failure"),
             ("E5_load_spike", "E5 Load spike"), ("E10_chaos_soak", "E10 Chaos soak (180 s)")]


def main():
    summary: dict = {"load_experiments": {}, "security": {}, "consistency": {}, "alerts": {}}
    md: list[str] = ["# Experiment results (generated by scripts/analyze.py)\n"]

    # ------------------------------------------------ fault-injection table
    md.append("## Fault-injection experiments: baseline vs resilient\n")
    md.append("Values are means over repetitions (min-max in brackets). Window = from fault injection to end of run.\n")
    md.append("| Experiment | Config | Runs | Requests | Window success | Failed req. | Degraded | p95 latency | "
              "Impact duration | Detection (alert) | Component recovery |")
    md.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for exp, title in LOAD_EXPS:
        summary["load_experiments"][exp] = {}
        for mode in ("baseline", "resilient"):
            runs = load(mode, exp)
            if not runs:
                continue
            row = {k: agg(runs, k) for k in ("requests", "success_ratio", "window_success_ratio", "failed",
                                             "degraded", "latency_avg_ms", "latency_p95_ms", "impact_duration_s",
                                             "detection_s", "container_recovery_s", "mttr_instance_s",
                                             "read_success_ratio", "write_success_ratio", "collateral_failures",
                                             "dashboard_p95_ms_during_fault", "cb_open_s")}
            if exp == "E5_load_spike":
                row["spike"] = {k: agg(runs, k, "spike") for k in ("requests", "success_ratio", "failed",
                                                                   "latency_avg_ms", "latency_p95_ms",
                                                                   "latency_p99_ms", "send_rate_rps")}
            if exp == "E10_chaos_soak":
                row["crashes"] = runs[0]["summary"].get("crashes")
                row["observed_mtbf_s"] = runs[0]["summary"].get("observed_mtbf_s")
            row["integrity"] = runs[-1]["summary"].get("integrity")
            # integrity over all repetitions, served-OK requests after the fault, alerts per run
            row["integrity_all"] = {
                "duplicate_rows": sum(r["summary"]["integrity"]["duplicate_rows"] for r in runs),
                "balance_mismatches": sum(r["summary"]["integrity"]["balance_mismatches"] for r in runs)}
            row["window_ok"] = {"mean": round(statistics.mean(
                r["summary"].get("window_requests", 0) * (r["summary"].get("window_success_ratio") or 0) for r in runs), 1),
                "min": 0, "max": 0, "n": 1}
            row["window_error_rate"] = {"mean": round(1 - row["window_success_ratio"]["mean"], 4), "min": 0, "max": 0,
                                        "n": 1} if row["window_success_ratio"] else None
            alerts = []
            for r in runs:
                fired = sorted({k.split("#")[0] for k, a in (r.get("alerts") or {}).items() if "firing" in a})
                alerts.append(fired)
            names = sorted({a.split("{")[0] for run in alerts for a in run})
            row["alerts"] = {"per_run": [len(a) for a in alerts], "names": names,
                             "distinct": sorted({a for run in alerts for a in run})}
            summary["load_experiments"][exp][mode] = row
            md.append(f"| {title} | {mode} | {len(runs)} | {fmt(row['requests'], digits=0)} | "
                      f"{fmt(row['window_success_ratio'], pct=True, digits=2)} | {fmt(row['failed'], digits=0)} | "
                      f"{fmt(row['degraded'], digits=0)} | {fmt(row['latency_p95_ms'], ' ms', digits=0)} | "
                      f"{fmt(row['impact_duration_s'], ' s')} | {fmt(row['detection_s'], ' s')} | "
                      f"{fmt(row['container_recovery_s'] or row['mttr_instance_s'], ' s')} |")
    md.append("")

    # ------------------------------------------------------------ E6 alerts
    for mode in ("resilient", "baseline"):
        runs = load(mode, "E6_alert_test")
        if runs:
            s = runs[0]["summary"]
            summary["alerts"][mode] = {"checks": s["alert_checks"], "unexpected": s["unexpected_alerts"]}
    if "resilient" in summary["alerts"]:
        md.append("## E6 Monitoring / alert validation (resilient)\n")
        md.append("| Alert (expected) | Injected at | Fired | Detection delay | Resolved at |")
        md.append("|---|---|---|---|---|")
        for k, v in summary["alerts"]["resilient"]["checks"].items():
            md.append(f"| {k} | t={v['injected_at']} s | {'yes' if v['fired'] else 'NO'} | "
                      f"{v['detection_s'] if v['detection_s'] is not None else '-'} s | {v['resolved_at'] or '-'} |")
        md.append(f"\nUnexpected (false-positive) alerts: {summary['alerts']['resilient']['unexpected'] or 'none'}\n")

    # ------------------------------------------------------------ E7 / E8
    for exp in ("E7_unauthorized_access", "E8_abuse_malformed"):
        summary["security"][exp] = {m: (load(m, exp)[0]["summary"] if load(m, exp) else None)
                                    for m in ("baseline", "resilient")}
    e7 = summary["security"]["E7_unauthorized_access"]
    if e7["baseline"] and e7["resilient"]:
        md.append("## E7 Unauthorized access\n")
        md.append("| Case | Request | Expected | Baseline status | Resilient status | Resilient result |")
        md.append("|---|---|---|---|---|---|")
        for b, r in zip(e7["baseline"]["cases"], e7["resilient"]["cases"]):
            md.append(f"| {r['case']} | `{r['request']}` | {r['expected']} | {b['status']}"
                      f"{' (data exposed)' if b['data_exposed'] else ''} | {r['status']} | "
                      f"{'PASS' if r['passed'] else 'FAIL'} |")
        for m in ("baseline", "resilient"):
            s = e7[m]
            md.append(f"\n{m}: {s['passed']}/{s['total']} denied as expected, data exposed in {s['data_exposed']} "
                      f"cases, grades changed: {s['grades_changed']}, unauthorized payments: {s['payments_created']}, "
                      f"audit 'denied' events: {s['audit_denied_events']}")
        md.append("")
    e8 = summary["security"]["E8_abuse_malformed"]
    if e8["baseline"] and e8["resilient"]:
        md.append("## E8 Abusive and malformed requests\n")
        md.append("| Case | Baseline status | Resilient status |")
        md.append("|---|---|---|")
        for b, r in zip(e8["baseline"]["cases"], e8["resilient"]["cases"]):
            md.append(f"| {r['case']} | {b['status']} | {r['status']} |")
        for m in ("baseline", "resilient"):
            s = e8[m]
            md.append(f"\n{m}: rejected {s['rejected']}/{s['total']}, server errors {s['server_errors']}, "
                      f"invalid payments stored {s['invalid_payments_stored']}, invalid grades stored "
                      f"{s['invalid_grades_stored']}; burst {s['burst']}; login brute force "
                      f"{s['login_bruteforce_status_counts']}; all containers running {s['all_containers_running']}")
        md.append("")

    # ------------------------------------------------------------------ E9
    for m in ("baseline", "resilient"):
        r = load(m, "E9_consistency")
        summary["consistency"][m] = r[0]["summary"] if r else None
    if summary["consistency"]["baseline"] and summary["consistency"]["resilient"]:
        md.append("## E9 Recovery and consistency (payments)\n")
        md.append("| Phase | Config | Logical payments | Acknowledged | Attempts | Payment rows | Duplicate rows | "
                  "Lost (acked) | Balance mismatches |")
        md.append("|---|---|---|---|---|---|---|---|---|")
        for phase in summary["consistency"]["resilient"]:
            for m in ("baseline", "resilient"):
                p = summary["consistency"][m][phase]
                md.append(f"| {phase} | {m} | {p['logical_payments']} | {p['acknowledged']} | {p['attempts_total']} | "
                          f"{p['payment_rows']} | {p['duplicate_rows']} | {p['lost_acknowledged']} | "
                          f"{p['balance_mismatches']} |")
        md.append("")

    # ------------------------------------------------------- reliability
    rel = reliability(summary)
    summary["reliability"] = rel
    md.append("## Reliability metrics (midterm analysis)\n")
    md.append("```\n" + json.dumps(rel, indent=1) + "\n```\n")

    (ROOT / "results" / "summary.json").write_text(json.dumps(summary, indent=1, default=str), encoding="utf-8")
    (ROOT / "results" / "results_tables.md").write_text("\n".join(md), encoding="utf-8")
    figures(summary)
    print("\n".join(md))


def reliability(summary: dict) -> dict:
    """Combine assumed component failure rates (MTTF) with measured MTTR values."""
    out: dict = {}
    soak = summary["load_experiments"].get("E10_chaos_soak", {})
    for mode in ("baseline", "resilient"):
        s = soak.get(mode)
        if not s:
            continue
        crashes = s.get("crashes") or []
        out[mode] = {
            "soak_duration_s": 180, "injected_failures": len(crashes),
            "observed_failure_rate_per_hour": round(len(crashes) / 180 * 3600, 1),
            "observed_mtbf_s": s.get("observed_mtbf_s"),
            "measured_mttr_instance_s": (s.get("mttr_instance_s") or {}).get("mean"),
            "measured_availability_requests": (s.get("success_ratio") or {}).get("mean"),
        }
    # measured MTTR per component from E1/E4 (means)
    e1 = summary["load_experiments"].get("E1_instance_crash", {})
    e4 = summary["load_experiments"].get("E4_database_failure", {})
    mttr = {m: {"app_instance_s": ((e1.get(m) or {}).get("container_recovery_s") or {}).get("mean"),
                "database_s": ((e4.get(m) or {}).get("container_recovery_s") or {}).get("mean")}
            for m in ("baseline", "resilient")}
    # assumed MTTF (documented assumptions, report section 2)
    mttf_h = {"gateway": 4380.0, "app_instance": 720.0, "database": 2190.0}

    def a(mttf_h_, mttr_s):
        mttr_h = (mttr_s or 0) / 3600
        return mttf_h_ / (mttf_h_ + mttr_h)

    model = {}
    # "baseline_manual": the same baseline with a realistic human MTTR (assumption: 15 min for an
    # application restart, 30 min for the database) instead of the optimistic 10-s simulated operator
    mttr["baseline_manual"] = {"app_instance_s": 900.0, "database_s": 1800.0}
    for m in ("baseline", "baseline_manual", "resilient"):
        r_app = mttr[m]["app_instance_s"] or 0
        r_db = mttr[m]["database_s"] or 0
        a_gw = a(mttf_h["gateway"], 60 if m == "resilient" else 600)
        a_inst = a(mttf_h["app_instance"], r_app)
        a_db = a(mttf_h["database"], r_db)
        if m.startswith("baseline"):
            a_svc = a_inst                         # one instance per service
            a_data = a_db
        else:
            a_svc = 1 - (1 - a_inst) ** 2          # two replicas in parallel
            a_data = a_db                          # replica serves reads only: writes still need primary
        a_sys = a_gw * (a_svc ** 3) * a_data       # 3 critical services in series (timetable non-critical)
        model[m] = {"A_gateway": round(a_gw, 7), "A_service": round(a_svc, 9), "A_database": round(a_db, 7),
                    "U_instance": f"{1 - a_inst:.2e}", "U_service": f"{1 - a_svc:.2e}",
                    "A_system": round(a_sys, 7), "downtime_min_per_year": round((1 - a_sys) * 525600, 1),
                    "MTTR_app_s": r_app, "MTTR_db_s": r_db}
    return {"soak": out, "measured_mttr": mttr, "assumed_mttf_hours": mttf_h, "availability_model": model}


def timeline(ax_ok, ax_lat, exp: str, events_for: str = "resilient"):
    for mode in ("baseline", "resilient"):
        runs = load(mode, exp)
        if not runs:
            continue
        ts = runs[0]["timeseries"]
        t = [b["t"] for b in ts]
        ratio = [(b["ok"] / max(1, b["ok"] + b["failed"])) * 100 for b in ts]
        ax_ok.plot(t, ratio, color=COLORS[mode], lw=2, label=mode)
        ax_lat.plot(t, [b["p95_ms"] or 0 for b in ts], color=COLORS[mode], lw=2, label=mode)
        if mode == events_for or len(runs[0]["events"]) and mode == "baseline":
            pass
    ev = (load("resilient", exp) or load("baseline", exp))[0]["events"]
    for e in ev:
        if e["name"].startswith(("docker stats",)):
            continue
        for ax in (ax_ok, ax_lat):
            ax.axvline(e["t"], color=INK2, lw=0.8, ls="--")
        ax_ok.text(e["t"] + 0.4, 4, e["name"], rotation=90, va="bottom", fontsize=7, color=INK2)
    ax_ok.set_ylim(0, 105)
    ax_ok.set_ylabel("successful requests, %")
    ax_lat.set_ylabel("p95 latency, ms")
    ax_lat.set_xlabel("time since start of run, s")


def figures(summary: dict):
    titles = dict(LOAD_EXPS)
    for exp in ("E1_instance_crash", "E2_node_failure", "E3_dependency_timeout", "E4_database_failure",
                "E5_load_spike", "E10_chaos_soak"):
        if not (load("baseline", exp) or load("resilient", exp)):
            continue
        fig, (a1, a2) = plt.subplots(2, 1, figsize=(7.2, 4.6), sharex=True, gridspec_kw={"height_ratios": [3, 2]})
        timeline(a1, a2, exp)
        a1.set_title(f"{titles[exp]}: per-second success ratio and p95 latency (rep 1)", loc="left",
                     fontsize=10, color=INK)
        a1.legend(loc="center right", ncol=1)
        fig.tight_layout()
        fig.savefig(FIG / f"{exp}.png")
        plt.close(fig)

    # availability during fault window, grouped bars
    labels, b_vals, r_vals = [], [], []
    for exp, title in LOAD_EXPS:
        d = summary["load_experiments"].get(exp, {})
        if "baseline" in d and "resilient" in d:
            labels.append(title.split(" ", 1)[0])
            b_vals.append((d["baseline"]["window_success_ratio"] or {"mean": 0})["mean"] * 100)
            r_vals.append((d["resilient"]["window_success_ratio"] or {"mean": 0})["mean"] * 100)
    if labels:
        fig, ax = plt.subplots(figsize=(7.2, 3.2))
        x = range(len(labels))
        w = 0.38
        bb = ax.bar([i - w / 2 - 0.01 for i in x], b_vals, w, color=COLORS["baseline"], label="baseline")
        rb = ax.bar([i + w / 2 + 0.01 for i in x], r_vals, w, color=COLORS["resilient"], label="resilient")
        for bars in (bb, rb):
            for rect in bars:
                ax.text(rect.get_x() + rect.get_width() / 2, rect.get_height() + 1, f"{rect.get_height():.1f}",
                        ha="center", fontsize=7, color=INK)
        ax.set_xticks(list(x), labels)
        ax.set_ylim(0, 110)
        ax.set_ylabel("successful requests after fault, %")
        ax.set_title("Request success ratio from fault injection to end of run", loc="left", fontsize=10, color=INK)
        ax.legend(loc="lower left", ncol=2)
        fig.tight_layout()
        fig.savefig(FIG / "availability_comparison.png")
        plt.close(fig)


if __name__ == "__main__":
    main()
